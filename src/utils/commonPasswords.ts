/**
 * Normalizes l33t speak substitutions to detect masked common passwords.
 * e.g., "P@$$w0rd" -> "password"
 */
export function normalizeLeetSpeak(input: string): string {
  let normalized = input.toLowerCase();
  for (const [char, replacement] of Object.entries(COMMON_SUBSTITUTIONS)) {
    normalized = normalized.split(char).join(replacement);
  }
  return normalized;
}
